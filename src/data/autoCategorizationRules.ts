// ─── Helpers ─────────────────────────────────────────────────────────────────

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function normalizeStr(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[''`]/g, "");
}

// ─── Compiled rule cache ──────────────────────────────────────────────────────

// Ordena: prioridade ASC, depois comprimento da keyword DESC (mais específica primeiro)
const SORTED_RULES = [...CATEGORIZATION_RULES].sort((a, b) => {
  if (a.priority !== b.priority) return a.priority - b.priority;
  return b.keyword.length - a.keyword.length;
});

// Pré-compila os regexes (word boundary + texto normalizado).
// Regras específicas (prioridade 1-2 com keyword de ≥5 letras) casam a keyword como
// PREFIXO de uma palavra maior — cobre nomes colados e plurais reais de extratos:
// "AutoPostoJardim", "IFOODCOM Agencia", "Supermercados Proença", "Batatas".
// Regras genéricas (prioridade 3, ou keywords curtas) mantêm fronteira estrita para
// evitar falsos positivos ("gas"→gastronomia, "oi"→oiapoque, "posto"→apostador).
// Keywords que, apesar de qualificarem, mantêm fronteira estrita — são prefixos de
// nomes de lugares/pessoas comuns ("Montes Claros", "Shellen", "Graalzinho").
const STRICT_PREFIX_DENYLIST = new Set(["claro", "shell", "graal"]);

const RULE_REGEXES: RegExp[] = SORTED_RULES.map((r) => {
  const norm = normalizeStr(r.keyword);
  const specific =
    r.priority <= 2 &&
    norm.replace(/\s/g, "").length >= 5 &&
    !STRICT_PREFIX_DENYLIST.has(norm);
  const tail = specific ? "" : "(?:\\b|$)";
  return new RegExp(`(?:^|\\b)${escapeRegex(norm)}${tail}`);
});

// ─── Public API ───────────────────────────────────────────────────────────────

/**
 * Aplica as regras de auto-categorização contra o thirdParty já extraído pelo parser.
 * Retorna o nome/alias da categoria ou null se nenhuma regra bater.
 * O retorno deve ser resolvido via resolveExpenseCategory() para obter o nome canônico.
 */
export function applyAutoCategorizationRules(thirdParty: string): string | null {
  const text = normalizeStr(thirdParty);

  for (let i = 0; i < SORTED_RULES.length; i++) {
    if (!RULE_REGEXES[i].test(text)) continue;

    const { excludeIf } = SORTED_RULES[i];
    if (excludeIf.length > 0) {
      const blocked = excludeIf.some((term) => text.includes(normalizeStr(term)));
      if (blocked) continue;
    }

    return SORTED_RULES[i].category;
  }
  return null;
}
